export const localSlugs = Object.keys(localPages)

export function getLocalPage(slug: string): LocalContent | null {
  return localPages[slug] ?? null
}

export function getAllLocalPages(): LocalContent[] {
  return Object.values(localPages)
}

/**
 * Local 頁索引閘門：以內容品質判斷，不再以客戶授權證據判斷。
 * 條件：production tier、非空服務方式聲明、≥4 個段落、≥5 題 FAQ、
 * 全頁文字量 ≥2,000 字。客戶案例（caseStudies）只影響展示，不影響索引。
 */
export function isIndexableLocalPage(page: LocalContent): boolean {
  return (
    page.qualityTier === 'production' &&
    page.coverageDisclosure.trim().length > 0 &&
    page.sections.length >= 4 &&
    page.faq.length >= 5 &&
    localContentLength(page) >= 2000
  )
}

function localContentLength(page: LocalContent): number {
  const sectionText = page.sections
    .map((s) => s.heading + s.body + (s.items?.join('') ?? ''))
    .join('')
  const faqText = page.faq.map((f) => f.question + f.answer).join('')
  return (page.intro + page.coverageDisclosure + sectionText + faqText).length
}
